// Release signing is read from keystore.properties (local, git-ignored) or
// environment variables in CI. No secrets are ever committed to this repo.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties()
if (keystorePropertiesFile.exists()) {
    FileInputStream(keystorePropertiesFile).use { keystoreProperties.load(it) }
}

fun signingValue(name: String): String? =
    keystoreProperties.getProperty(name) ?: System.getenv(name)

val hasReleaseSigning = signingValue("KEYSTORE_FILE") != null &&
    signingValue("KEYSTORE_PASSWORD") != null &&
    signingValue("KEY_ALIAS") != null &&
    signingValue("KEY_PASSWORD") != null

